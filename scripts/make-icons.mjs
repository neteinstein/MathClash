// Renders the app icon (assets/icon-mark.svg) into every PNG the web app and
// the Android project need. Uses the Playwright Chromium:  npm run icons
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mark = readFileSync(join(root, 'assets/icon-mark.svg'), 'utf8').replace(/<!--.*?-->/s, '');
const BG = '#1a1240';

/** Builds an SVG: background shape + the mark scaled around the centre. */
function svg({ shape = 'rounded', scale = 1 } = {}) {
  const bg =
    shape === 'none' ? '' :
    shape === 'circle' ? `<circle cx="256" cy="256" r="256" fill="${BG}"/>` :
    shape === 'square' ? `<rect width="512" height="512" fill="${BG}"/>` :
    `<rect width="512" height="512" rx="112" fill="${BG}"/>`;
  const t = `translate(256 256) scale(${scale}) translate(-256 -256)`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${bg}<g transform="${t}">${mark}</g></svg>`;
}

const browser = await chromium.launch();
const page = await browser.newPage();

async function png(svgText, size, out, { bg = 'transparent', canvas = size, markSize = size } = {}) {
  await page.setViewportSize({ width: canvas, height: canvas });
  const off = (canvas - markSize) / 2;
  await page.setContent(
    `<html><body style="margin:0;background:${bg}"><div style="position:absolute;left:${off}px;top:${off}px;width:${markSize}px;height:${markSize}px">${svgText.replace('<svg ', '<svg width="100%" height="100%" ')}</div></body></html>`,
  );
  mkdirSync(dirname(out), { recursive: true });
  await page.screenshot({ path: out, omitBackground: bg === 'transparent' });
  console.log('wrote', out.replace(root + '/', ''));
}

// ---- web
writeFileSync(join(root, 'public/favicon.svg'), svg());
await png(svg(), 192, join(root, 'public/icons/icon-192.png'));
await png(svg(), 512, join(root, 'public/icons/icon-512.png'));
await png(svg({ shape: 'square', scale: 0.78 }), 512, join(root, 'public/icons/maskable-512.png'));
await png(svg({ shape: 'square', scale: 0.86 }), 180, join(root, 'public/icons/apple-touch-icon.png'));

// ---- android (only if the native project exists)
const res = join(root, 'android/app/src/main/res');
if (existsSync(res)) {
  const dens = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
  for (const [d, k] of Object.entries(dens)) {
    await png(svg(), 48 * k, join(res, `mipmap-${d}/ic_launcher.png`));
    await png(svg({ shape: 'circle', scale: 0.92 }), 48 * k, join(res, `mipmap-${d}/ic_launcher_round.png`));
    // Adaptive icon foreground: 108dp canvas, content inside the 66dp safe zone.
    await png(svg({ shape: 'none', scale: 0.62 }), 108 * k, join(res, `mipmap-${d}/ic_launcher_foreground.png`));
  }
  // Splash images generated by the Capacitor template: keep their sizes, redraw them.
  for (const dir of readdirSync(res).filter((f) => f.startsWith('drawable'))) {
    const file = join(res, dir, 'splash.png');
    if (!existsSync(file)) continue;
    const buf = readFileSync(file);
    const w = buf.readUInt32BE(16);
    const h = buf.readUInt32BE(20);
    const size = Math.round(Math.min(w, h) * 0.32);
    await page.setViewportSize({ width: w, height: h });
    await page.setContent(
      `<html><body style="margin:0;background:${BG};display:grid;place-items:center;height:${h}px">${svg({ shape: 'none' }).replace('<svg ', `<svg width="${size}" height="${size}" `)}</body></html>`,
    );
    await page.screenshot({ path: file });
    console.log('wrote', file.replace(root + '/', ''), `${w}x${h}`);
  }
}

await browser.close();
